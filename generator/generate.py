"""Generate InSpec profiles and Chef remediation cookbooks from benchmark YAML.

Usage:
    python -m generator                      # every benchmarks/*.yml -> build/
    python -m generator benchmarks/x.yml --out build

One benchmark YAML file produces:
    build/profiles/<name>/            InSpec profile (scan)
    build/cookbooks/<name>_remediation/  Chef Infra cookbook (fix), if any rule is remediable
"""
from __future__ import annotations

import argparse
import re
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path
from textwrap import indent

import yaml

from .rules import RULE_TYPES, Rule, RuleError, rb

ROOT = Path(__file__).resolve().parents[1]
GENERATED_BY = "GENERATED by generator/generate.py from {src} - DO NOT EDIT BY HAND."

PLATFORMS = {
    "debian": [{"platform-family": "debian"}],
    "aws": [{"platform": "aws"}],
}
DEPENDENCIES = {
    "inspec-aws": {
        "name": "inspec-aws",
        "url": "https://github.com/inspec/inspec-aws/archive/main.tar.gz",
    },
}


class BenchmarkError(ValueError):
    """Raised when a benchmark file is invalid."""


@dataclass(frozen=True)
class Benchmark:
    name: str
    title: str
    version: str
    platform: str
    maintainer: str
    source: str
    rules: tuple[Rule, ...]

    @property
    def cookbook(self) -> str:
        return self.name.replace("-", "_") + "_remediation"


RULE_FIELDS = {"id", "title", "impact", "type", "params", "rationale", "tags"}


def _one_line(value, what: str, max_len: int = 200) -> str:
    text = " ".join(str(value or "").split())
    if not text or len(text) > max_len:
        raise BenchmarkError(f"{what} must be 1-{max_len} characters")
    return text


def load_benchmark(path: Path) -> Benchmark:
    data = yaml.safe_load(Path(path).read_text(encoding="utf-8")) or {}
    meta = data.get("benchmark") or {}
    raw_rules = data.get("rules") or []

    name = str(meta.get("name", ""))
    if not re.fullmatch(r"[a-z][a-z0-9-]*", name):
        raise BenchmarkError(f"benchmark.name {name!r} must be lowercase letters, digits, '-'")
    version = str(meta.get("version", ""))
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise BenchmarkError(f"benchmark.version {version!r} must look like 1.2.3")
    platform = meta.get("platform")
    if platform not in PLATFORMS:
        raise BenchmarkError(f"benchmark.platform must be one of {sorted(PLATFORMS)}")
    if not raw_rules:
        raise BenchmarkError("benchmark has no rules")

    rules, seen = [], set()
    for raw in raw_rules:
        rule_id = str(raw.get("id", ""))
        if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", rule_id):
            raise BenchmarkError(f"rule id {rule_id!r} must look like 'ssh-01'")
        if rule_id in seen:
            raise BenchmarkError(f"duplicate rule id {rule_id!r}")
        seen.add(rule_id)
        unknown = set(raw) - RULE_FIELDS
        if unknown:
            raise BenchmarkError(f"{rule_id}: unknown fields {sorted(unknown)}")
        rtype = raw.get("type")
        if rtype not in RULE_TYPES:
            raise BenchmarkError(f"{rule_id}: unknown type {rtype!r}; known: {sorted(RULE_TYPES)}")
        impact = raw.get("impact")
        if isinstance(impact, bool) or not isinstance(impact, (int, float)) or not 0 <= impact <= 1:
            raise BenchmarkError(f"{rule_id}: impact must be a number from 0.0 to 1.0")
        tags = tuple(str(t) for t in raw.get("tags") or ())
        for tag in tags:
            if not re.fullmatch(r"[a-z0-9-]+", tag):
                raise BenchmarkError(f"{rule_id}: invalid tag {tag!r}")

        rule = Rule(
            id=rule_id,
            title=_one_line(raw.get("title"), f"{rule_id}: title", 120),
            impact=float(impact),
            type=rtype,
            params=dict(raw.get("params") or {}),
            rationale=" ".join(str(raw.get("rationale") or "").split()),
            tags=tags,
        )
        try:
            RULE_TYPES[rtype].validate(rule)
        except RuleError as exc:
            raise BenchmarkError(str(exc)) from exc
        rules.append(rule)

    return Benchmark(
        name=name,
        title=_one_line(meta.get("title"), "benchmark.title"),
        version=version,
        platform=platform,
        maintainer=_one_line(meta.get("maintainer", "Compliance Automation"), "maintainer"),
        source=Path(path).name,
        rules=tuple(rules),
    )


def _remediable(bench: Benchmark) -> list[Rule]:
    return [r for r in bench.rules if RULE_TYPES[r.type].chef(r) is not None]


def render_control(bench: Benchmark, rule: Rule) -> str:
    rtype = RULE_TYPES[rule.type]
    fix = f"{bench.cookbook}::default" if rtype.chef(rule) else "none (scan-only)"
    lines = [
        f"control {rb(rule.id)} do",
        f"  impact {rule.impact!r}",
        f"  title {rb(rule.title)}",
    ]
    if rule.rationale:
        lines.append(f"  desc {rb(rule.rationale)}")
    if rule.tags:
        lines.append("  tag " + ", ".join(rb(t) for t in rule.tags))
    lines.append(f"  tag remediation: {rb(fix)}")
    lines.append(indent(rtype.inspec(rule), "  "))
    lines.append("end")
    return "\n".join(lines)


def render_profile(bench: Benchmark) -> dict[str, str]:
    base = f"profiles/{bench.name}"
    header = "# " + GENERATED_BY.format(src=f"benchmarks/{bench.source}")

    meta: dict = {
        "name": bench.name,
        "title": bench.title,
        "maintainer": bench.maintainer,
        "copyright": bench.maintainer,
        "license": "Apache-2.0",
        "summary": f"{bench.title} (auto-generated, {len(bench.rules)} controls)",
        "version": bench.version,
        "supports": PLATFORMS[bench.platform],
    }
    deps = sorted({d for r in bench.rules for d in RULE_TYPES[r.type].dependencies})
    if deps:
        meta["depends"] = [DEPENDENCIES[d] for d in deps]
    inputs: dict[str, dict] = {}
    for rule in bench.rules:
        for inp in RULE_TYPES[rule.type].inputs(rule):
            prev = inputs.setdefault(inp["name"], inp)
            if prev["value"] != inp["value"]:
                raise BenchmarkError(f"input {inp['name']!r} has conflicting defaults")
    if inputs:
        meta["inputs"] = list(inputs.values())

    controls = "\n\n".join(render_control(bench, r) for r in bench.rules)
    rows = "\n".join(
        f"| `{r.id}` | {r.title} | {r.impact} | "
        f"{'Chef' if RULE_TYPES[r.type].chef(r) else 'scan-only'} |"
        for r in bench.rules
    )
    readme = (
        f"# {bench.title}\n\n"
        f"_{GENERATED_BY.format(src=f'benchmarks/{bench.source}')}_\n\n"
        f"| Control | Title | Impact | Remediation |\n|---|---|---|---|\n{rows}\n"
    )
    return {
        f"{base}/inspec.yml": f"{header}\n"
        + yaml.safe_dump(meta, sort_keys=False, default_flow_style=False),
        f"{base}/controls/generated.rb": f"{header}\n\n{controls}\n",
        f"{base}/README.md": readme,
    }


SETTING_HELPERS = r"""# Last uncommented value of +key+ in a whitespace-separated config file.
read_setting = lambda do |path, key|
  next nil unless ::File.exist?(path)
  line = ::File.readlines(path).grep(/^\s*#{Regexp.escape(key)}\s+/i).last
  line && line.split[1]
end

# Replace every uncommented "key ..." line, or append one if none exists.
write_setting = lambda do |path, key, value|
  pattern = /^\s*#{Regexp.escape(key)}\s+.*$/i
  edit = Chef::Util::FileEdit.new(path)
  edit.search_file_replace_line(pattern, "#{key} #{value}")
  edit.insert_line_if_no_match(pattern, "#{key} #{value}")
  edit.write_file
end
"""


def render_cookbook(bench: Benchmark) -> dict[str, str]:
    fixable = _remediable(bench)
    if not fixable:
        return {}
    base = f"cookbooks/{bench.cookbook}"
    header = "# " + GENERATED_BY.format(src=f"benchmarks/{bench.source}")
    metadata = "\n".join([
        header,
        f"name {rb(bench.cookbook)}",
        f"maintainer {rb(bench.maintainer)}",
        "license 'Apache-2.0'",
        f"description {rb('Remediation for ' + bench.title)}",
        f"version {rb(bench.version)}",
        "chef_version '>= 16.0'",
        "supports 'ubuntu'",
        "",
    ])
    parts = [
        header,
        "#",
        "# Every resource is idempotent: guards skip it when the node is already",
        "# compliant, so a second Chef run must report 0 resources updated.",
        "",
    ]
    if any(RULE_TYPES[r.type].uses_setting_helpers for r in fixable):
        parts.append(SETTING_HELPERS)
    for rule in fixable:
        parts.append(f"# {rule.id} (impact {rule.impact!r})")
        parts.append(RULE_TYPES[rule.type].chef(rule))
        parts.append("")
    return {
        f"{base}/metadata.rb": metadata,
        f"{base}/recipes/default.rb": "\n".join(parts),
    }


def render_benchmark(bench: Benchmark) -> dict[str, str]:
    return {**render_profile(bench), **render_cookbook(bench)}


def generate_all(sources: list[Path], out: Path, clean: bool = True) -> dict[str, str]:
    files: dict[str, str] = {}
    for src in sources:
        rendered = render_benchmark(load_benchmark(src))
        clash = files.keys() & rendered.keys()
        if clash:
            raise BenchmarkError(f"two benchmarks write the same files: {sorted(clash)}")
        files.update(rendered)
    if clean and out.exists():
        shutil.rmtree(out)
    for rel, content in sorted(files.items()):
        target = out / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("benchmarks", nargs="*", type=Path)
    parser.add_argument("--out", type=Path, default=ROOT / "build")
    args = parser.parse_args(argv)
    sources = args.benchmarks or sorted((ROOT / "benchmarks").glob("*.yml"))
    try:
        files = generate_all(sources, args.out)
    except (BenchmarkError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    for rel in sorted(files):
        print(f"  wrote {args.out.name}/{rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
